#!/usr/bin/env python3
"""Cut lift_fixture.h from the 2026-11-11 lift captures (TER-U34).

Usage: lift_fixture.py <capture 1 log> <capture 2 log> > lift_fixture.h

The captures are TERRAIN_CAPTURE=1 dashboard logs: every accelerometer
sample, car axes, gains applied, before the bias, in cm/s^2. The logs stay
out of the repository; this keeps the stretches the tests need.
"""
import re
import sys

# (name, capture, from s, to s, level reading mm/s^2, LIFTED, OVERTURNED);
# a count of -1 means "at least one", -2 "any number".
LEVEL_1 = (-551, -2428, 8082)
LEVEL_2 = (-405, -2125, 7976)
SEGMENTS = [
    ("floor", 2, 142.7, 186.0, LEVEL_2, 0, 0),
    ("moving_1", 2, 185.7, 187.7, LEVEL_2, -1, 0),
    ("moving_2", 2, 198.7, 200.7, LEVEL_2, -1, 0),
    ("moving_3", 2, 216.9, 218.9, LEVEL_2, -1, 0),
    ("moving_4", 2, 236.9, 238.9, LEVEL_2, -1, 0),
    ("moving_5", 2, 255.8, 257.8, LEVEL_2, -1, 0),
    ("stopped_1", 2, 274.4, 276.4, LEVEL_2, -1, 0),
    ("stopped_2", 2, 286.1, 288.1, LEVEL_2, -1, 0),
    ("stopped_3", 2, 298.3, 300.3, LEVEL_2, -1, 0),
    ("upside_down", 2, 312.0, 319.0, LEVEL_2, -2, -1),
    ("on_side", 1, 47.5, 58.5, LEVEL_1, -2, -1),
    ("gentle", 1, 20.0, 25.5, LEVEL_1, 0, 0),
]


def load(path):
    samples = []
    for line in open(path):
        m = re.search(r"console (\d+) terrain: IMU n=\d+ d=\d+ w=-?\d+ (.*)$",
                      line)
        if not m:
            continue
        first_ms = int(m.group(1)) - 100
        for i, triple in enumerate(m.group(2).split()):
            x, y, z = (int(v) for v in triple.split(","))
            samples.append((first_ms + 10 * (i + 1), x, y, z))
    return samples


def main():
    captures = {1: load(sys.argv[1]), 2: load(sys.argv[2])}
    print("/* Generated by lift_fixture.py from the 2026-11-11 lift captures")
    print(" * (TER-U34): accelerometer samples in car axes, gains applied,")
    print(" * before the bias, cm/s^2, 100 a second. Do not edit. */")
    print()
    table = []
    for name, cap, start, end, level, lifted, over in SEGMENTS:
        cut = [s for s in captures[cap] if start <= s[0] / 1000.0 <= end]
        print("static int16_t const seg_%s[][3] = {" % name)
        for i in range(0, len(cut), 6):
            print("    " + " ".join("{%d, %d, %d}," % s[1:]
                                    for s in cut[i:i + 6]))
        print("};")
        table.append('    {"%s", seg_%s, %d, {%d, %d, %d}, %d, %d},'
                     % (name, name, len(cut), level[0], level[1], level[2],
                        lifted, over))
    print()
    print("static lift_segment_t const segments[] = {")
    print("\n".join(table))
    print("};")


if __name__ == "__main__":
    main()
